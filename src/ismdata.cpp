const int ISM_COUNT = int(sizeof(kTable) / sizeof(kTable[0]));

const IsmEntry *findIsm(const char *id)
{
    if (!id) return nullptr;
    for (int i = 0; i < ISM_COUNT; ++i)
        if (std::strcmp(kTable[i].id, id) == 0)
            return &kTable[i];
    return nullptr;
}

