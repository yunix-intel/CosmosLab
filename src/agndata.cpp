const int AGN_COUNT = int(sizeof(kTable) / sizeof(kTable[0]));

const AgnEntry *findAgn(const char *id)
{
    if (!id) return nullptr;
    for (int i = 0; i < AGN_COUNT; ++i)
        if (std::strcmp(kTable[i].id, id) == 0)
            return &kTable[i];
    return nullptr;
}

